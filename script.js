function initPortfolioImageCarousel(carouselId, trackId, jsonFile) {
  const carousel = document.getElementById(carouselId);
  const track = document.getElementById(trackId);
  if (!carousel || !track) return;

  const prev = carousel.querySelector(".mma-projetos__arrow--prev");
  const next = carousel.querySelector(".mma-projetos__arrow--next");
  let slideIdx = 0;
  let maxIdx = 0;

  function createCard(p) {
    const tile = document.createElement("div");
    tile.className = "mma-projetos__tile";
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "project-open mma-projetos__open";
    btn.dataset.full = p.full;
    btn.dataset.alt = p.alt || "";
    btn.setAttribute("aria-label", "Abrir imagem em tamanho completo");
    const img = document.createElement("img");
    img.src = p.src;
    img.alt = p.alt || "";
    img.loading = "lazy";
    img.decoding = "async";
    if (p.width) img.width = p.width;
    if (p.height) img.height = p.height;
    btn.appendChild(img);
    tile.appendChild(btn);
    return tile;
  }

  fetch(new URL(`assets/${jsonFile}`, window.location.href).href)
    .then((r) => {
      if (!r.ok) throw new Error("fetch");
      return r.json();
    })
    .then((data) => {
      const items = data.projects || [];
      if (!items.length) return;
      const viewport = carousel.querySelector(".mma-projetos__viewport");
      maxIdx = Math.max(0, items.length - 1);
      track.innerHTML = "";
      items.forEach((p) => {
        const slide = document.createElement("div");
        slide.className = "mma-projetos__slide";
        slide.appendChild(createCard(p));
        track.appendChild(slide);
      });

      function slidesPerView() {
        return window.matchMedia("(max-width: 640px)").matches ? 1 : 2;
      }

      function getTrackGapPx() {
        const g = getComputedStyle(track).gap || "14px";
        const m = String(g).match(/([\d.]+)px/);
        return m ? parseFloat(m[1]) : 14;
      }

      function applyLayout() {
        if (!viewport) return;
        const gap = getTrackGapPx();
        const vw = viewport.clientWidth;
        const spv = slidesPerView();
        const slideW = spv === 1 ? vw : (vw - gap) / 2;
        track.querySelectorAll(".mma-projetos__slide").forEach((el) => {
          el.style.flex = `0 0 ${slideW}px`;
        });
        const step = slideW + gap;
        track.style.transform = `translate3d(-${slideIdx * step}px, 0, 0)`;
      }

      if (viewport && typeof ResizeObserver !== "undefined") {
        const ro = new ResizeObserver(() => applyLayout());
        ro.observe(viewport);
      } else {
        let t;
        window.addEventListener("resize", () => {
          clearTimeout(t);
          t = setTimeout(applyLayout, 100);
        });
      }

      const mqlMobile = window.matchMedia("(max-width: 640px)");
      const onBpChange = () => {
        slideIdx = Math.min(slideIdx, maxIdx);
        applyLayout();
      };
      if (typeof mqlMobile.addEventListener === "function") {
        mqlMobile.addEventListener("change", onBpChange);
      } else if (typeof mqlMobile.addListener === "function") {
        mqlMobile.addListener(onBpChange);
      }

      if (prev) {
        prev.addEventListener("click", () => {
          slideIdx = slideIdx <= 0 ? maxIdx : slideIdx - 1;
          applyLayout();
        });
      }
      if (next) {
        next.addEventListener("click", () => {
          slideIdx = slideIdx >= maxIdx ? 0 : slideIdx + 1;
          applyLayout();
        });
      }

      requestAnimationFrame(() => requestAnimationFrame(applyLayout));
    })
    .catch(() => {
      track.innerHTML =
        "<p class=\"mma-projetos__error\">Não foi possível carregar a galeria. Consulte o portfólio completo.</p>";
    });
}

/** Início (#projetos): carrossel horizontal na caixa, mesma escala de imagem que .mma-projetos__open nas fichas. */
function initHomePortfolioAutoplay() {
  const viewport = document.getElementById("homePortfolioAutoplayViewport");
  const track = document.getElementById("homePortfolioAutoplayTrack");
  if (!viewport || !track) return;

  const files = ["portfolio-metacrilato.json", "portfolio-epoxi.json", "portfolio-tapete.json"];
  const base = new URL("assets/", window.location.href).href;

  Promise.all(
    files.map((f) =>
      fetch(`${base}${f}`)
        .then((r) => (r.ok ? r.json() : { projects: [] }))
        .catch(() => ({ projects: [] }))
    )
  ).then((parts) => {
    const projects = parts.flatMap((d) => d.projects || []);
    if (!projects.length) {
      track.innerHTML =
        "<p class=\"mma-projetos__error\" style=\"padding:1.5rem;text-align:center;\">Não foi possível carregar imagens.</p>";
      return;
    }

    track.innerHTML = "";
    projects.forEach((p, i) => {
      const slide = document.createElement("div");
      slide.className = "home-portfolio-autoplay__slide";
      slide.setAttribute("aria-hidden", i === 0 ? "false" : "true");

      const btn = document.createElement("button");
      btn.type = "button";
      btn.className = "mma-projetos__open project-open";
      btn.dataset.full = p.full || p.src;
      btn.dataset.alt = p.alt || "";
      btn.setAttribute("aria-label", "Abrir imagem em tamanho completo");

      const img = document.createElement("img");
      img.src = p.src;
      img.alt = p.alt || "";
      img.loading = i === 0 ? "eager" : "lazy";
      img.decoding = "async";
      if (p.width) img.width = p.width;
      if (p.height) img.height = p.height;

      btn.appendChild(img);
      slide.appendChild(btn);
      track.appendChild(slide);
    });

    let idx = 0;
    const slides = () => [...track.querySelectorAll(".home-portfolio-autoplay__slide")];
    const n = projects.length;

    function applyLayout() {
      const w = viewport.clientWidth;
      if (!w) return;
      slides().forEach((el) => {
        el.style.flex = `0 0 ${w}px`;
        el.style.width = `${w}px`;
      });
      track.style.transform = `translate3d(-${idx * w}px, 0, 0)`;
    }

    function go(to) {
      idx = ((to % n) + n) % n;
      slides().forEach((el, i) => el.setAttribute("aria-hidden", i === idx ? "false" : "true"));
      applyLayout();
    }

    let resizeT;
    if (typeof ResizeObserver !== "undefined") {
      const ro = new ResizeObserver(() => {
        clearTimeout(resizeT);
        resizeT = setTimeout(applyLayout, 50);
      });
      ro.observe(viewport);
    } else {
      window.addEventListener("resize", () => {
        clearTimeout(resizeT);
        resizeT = setTimeout(applyLayout, 120);
      });
    }

    const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    if (!reduceMotion && n > 1) {
      setInterval(() => go(idx + 1), 5000);
    }

    requestAnimationFrame(() => requestAnimationFrame(applyLayout));
  });
}

